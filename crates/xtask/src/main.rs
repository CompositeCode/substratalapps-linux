//! Repo automation.
//!
//!   cargo xtask gen-help --out <specs>/help           write the Linux pages of the Hub help center
//!   cargo xtask gen-help --out <specs>/help --check   fail if they're out of date
//!
//! The Hub help center lives in the specs repo
//! (CompositeCode/substratalapps-applications-specs, `help/`) and is the one
//! documentation site for every Hub app. Most of it is generated there from
//! the specs and the API. The pages that come from this app's code are
//! generated here, so they always match what the Linux app does:
//!
//! | Page                                  | Source                                  |
//! |---------------------------------------|-----------------------------------------|
//! | guides/linux-keyboard-shortcuts.md    | substratal_core::shortcuts::SHORTCUTS   |
//! | developers/substratalctl.md           | substratalctl's clap definition         |
//!
//! `.github/workflows/docs-dispatch.yml` runs this on every push to main and
//! opens a pull request in the specs repo when a page changed.

use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::path::PathBuf;

use anyhow::{Context, Result, bail};
use clap::Parser;
use substratal_core::{shortcuts, version};

const SOURCE: &str = "GENERATED by `cargo xtask gen-help` in CompositeCode/substratalapps-linux. Don't edit here; change the app and regenerate.";

#[derive(Parser)]
enum Cmd {
    /// Write the Linux app's pages of the Hub help center.
    GenHelp {
        /// The specs repo's `help/` directory.
        #[arg(long)]
        out: PathBuf,
        /// Fail instead of writing when a page is out of date.
        #[arg(long)]
        check: bool,
    },
}

fn main() -> Result<()> {
    match Cmd::parse() {
        Cmd::GenHelp { out, check } => gen_help(out, check),
    }
}

fn gen_help(out: PathBuf, check: bool) -> Result<()> {
    if !out.join("guides").is_dir() {
        bail!(
            "{} doesn't look like the help center's help/ directory",
            out.display()
        );
    }
    let mut pages = BTreeMap::new();
    pages.insert("guides/linux-keyboard-shortcuts.md", shortcuts_page());
    pages.insert("developers/substratalctl.md", cli_page());

    let mut changed = Vec::new();
    for (rel, body) in &pages {
        let path = out.join(rel);
        if std::fs::read_to_string(&path).ok().as_deref() != Some(body.as_str()) {
            changed.push(*rel);
            if !check {
                std::fs::write(&path, body).with_context(|| path.display().to_string())?;
            }
        }
    }
    if check && !changed.is_empty() {
        bail!(
            "help pages out of date: {}\nRun `cargo xtask gen-help --out <specs>/help`.",
            changed.join(", ")
        );
    }
    println!(
        "gen-help: {} of {} pages {}",
        changed.len(),
        pages.len(),
        if check { "differ" } else { "written" }
    );
    Ok(())
}

fn shortcuts_page() -> String {
    let mut p = format!(
        "---\ntitle: Keyboard shortcuts on Linux\nsummary: Every keyboard shortcut in the Linux app, and what it does.\naudience: everyone\norder: 21\nscreens: [GLB-01]\n---\n\n<!-- {SOURCE} -->\n\n# Keyboard shortcuts on Linux\n\nEvery shortcut also has a visible button, menu item or command-palette entry. Press **Ctrl+?** in the app to see this list. See also [Substratal on Linux](linux.html).\n"
    );
    let mut group = "";
    for s in shortcuts::SHORTCUTS {
        if s.group != group {
            let _ = write!(p, "\n## {}\n\n| Keys | Does |\n|---|---|\n", s.group);
            group = s.group;
        }
        let keys: Vec<_> = s
            .accels
            .iter()
            .map(|a| format!("**{}**", shortcuts::display(a)))
            .collect();
        let _ = writeln!(p, "| {} | {} |", keys.join(" or "), s.label);
    }
    p
}

fn cli_page() -> String {
    let mut p = format!(
        "---\ntitle: substratalctl\nsummary: The Linux Hub's command-line companion: check the API, sign in, list users and look up screens from a terminal or script.\naudience: developer\norder: 10\n---\n\n<!-- {SOURCE} -->\n\n# substratalctl\n\n`substratalctl` uses the Linux app's code, so it signs in the same way, sends `Substratal-Version: {v}` on every request and gets the same errors. It's built with the app: `cargo build -p substratalctl`, or run it from the Flatpak with `flatpak run --command=substratalctl com.substratalapps.Hub`.\n\n## Examples\n\n```bash\nsubstratalctl health                        # GET /health\nsubstratalctl version                       # this client, the API version it sends, the base URL\nsubstratalctl login --email you@example.com # prompts for the password, then a 2FA code if needed\nsubstratalctl whoami --json\nsubstratalctl users list --query dana\nsubstratalctl route substratal://admin/users/usr_42\nsubstratalctl help-url KEY-03\n```\n\nOn a desktop the session goes into your keyring. On a server without one, pass `--no-keyring`; you then sign in on each run. Use `--api local` (or `SUBSTRATAL_API=local`) for the API's devserver on `localhost:8080`, or pass any base URL. On failure it exits with status 1 and prints the **request ID**, which you can quote to support.\n\n## Reference\n\n",
        v = version::API_VERSION
    );
    let md = clap_markdown::help_markdown_command(&substratalctl::command());
    // clap-markdown starts with its own H1 and a table of contents; keep the
    // sections, one level down under "Reference".
    let body: Vec<String> = md
        .lines()
        .skip_while(|l| !l.starts_with("## "))
        .map(|l| {
            if l.starts_with("## ") {
                format!("#{l}")
            } else {
                l.to_string()
            }
        })
        .collect();
    p.push_str(&body.join("\n"));
    p.push('\n');
    p
}
